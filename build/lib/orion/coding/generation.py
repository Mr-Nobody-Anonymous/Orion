@dataclass(frozen=True, slots=True)
class GeneratedCandidate:
    identifier: str
    kind: str  # "strategy" | "test" | "patch"
    source: str
    content_hash: str
    parameters: Mapping[str, Any]
    created_at: datetime

    @classmethod
    def create(cls, identifier: str, kind: str, source: str, parameters: Mapping[str, Any]) -> "GeneratedCandidate":
        if not identifier.strip():
            raise ValueError("identifier is required")
        if kind not in {"strategy", "test", "patch"}:
            raise ValueError("kind must be strategy, test, or patch")
        return cls(
            identifier=identifier,
            kind=kind,
            source=source,
            content_hash=sha256(source.encode("utf-8")).hexdigest(),
            parameters=dict(parameters),
            created_at=datetime.now(timezone.utc),
        )


class StrategyCodeGenerator:
    """Deterministic strategy synthesis from parameters.

    Identical parameters produce byte-identical candidates, so every
    generation event is reproducible and auditable.
    """

    def generate(
        self,
        name: str,
        *,
        lookback: int = 3,
        entry_threshold: float = 0.01,
        exit_threshold: float = 0.005,
        hypothesis: str = "short-horizon momentum persists",
    ) -> GeneratedCandidate:
        if lookback < 2:
            raise ValueError("lookback must be at least two")
        if not 0 < entry_threshold <= 1 or not 0 <= exit_threshold < entry_threshold:
            raise ValueError("thresholds must satisfy 0 <= exit < entry <= 1")
        source = STRATEGY_TEMPLATE.format(
            name=name,
            lookback=lookback,
            entry_threshold=repr(entry_threshold),
            exit_threshold=repr(exit_threshold),
            hypothesis=hypothesis.replace('"', "'"),
            created_at="generation-time",  # deterministic: timestamp excluded from source
        )
        return GeneratedCandidate.create(
            f"candidate:{name}", "strategy", source,
            {"lookback": lookback, "entry_threshold": entry_threshold, "exit_threshold": exit_threshold},
        )

    def generate_tests(self, candidate: GeneratedCandidate, *, module_under_test: str = "candidate_strategy") -> GeneratedCandidate:
        if candidate.kind != "strategy":
            raise ValueError("tests can only be generated for strategy candidates")
        lookback = int(candidate.parameters.get("lookback", 3))
        source = TEST_TEMPLATE.format(
            name=candidate.identifier,
            lookback=lookback,
            module_under_test=module_under_test,
        )
        return GeneratedCandidate.create(f"tests:{candidate.identifier}", "test", source, {"module": module_under_test})

    def variant_grid(
        self,
        base_name: str,
        *,
        lookbacks: Sequence[int] = (2, 3, 5),
        entry_thresholds: Sequence[float] = (0.005, 0.01, 0.02),
    ) -> tuple[GeneratedCandidate, ...]:
        """Generate a population of strategy candidates for the evolution engine."""
        if not lookbacks or not entry_thresholds:
            raise ValueError("lookbacks and entry_thresholds must be non-empty")
        candidates: list[GeneratedCandidate] = []
        for lookback in lookbacks:
            for threshold in entry_thresholds:
                candidates.append(self.generate(
                    f"{base_name}-lb{lookback}-et{threshold}",
                    lookback=lookback,
                    entry_threshold=threshold,
                ))
        return tuple(candidates)
